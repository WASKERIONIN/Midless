typedef struct { const unsigned char *d; int len; } VoxCtx;

static bool vox_walk(VoxCtx *c, int pos, int end, VoxData *out, int depth) {
    if (depth > 8) return false;
    while (pos + 12 <= end) {
        const unsigned char *p = c->d + pos;
        char id[5] = { (char)p[0], (char)p[1], (char)p[2], (char)p[3], 0 };
        int n = (int)vox_rd32(p + 4);
        int m = (int)vox_rd32(p + 8);
        int body = pos + 12;
        int children = body + n;
        if (n < 0 || m < 0 || body > end || children + m > end) return false;
        if (strcmp(id, "SIZE") == 0) {
            if (n < 12) return false;
            out->sx = (int)vox_rd32(c->d + body);
            out->sy = (int)vox_rd32(c->d + body + 4);
            out->sz = (int)vox_rd32(c->d + body + 8);
        } else if (strcmp(id, "XYZI") == 0) {
            if (n < 4) return false;
            int count = (int)vox_rd32(c->d + body);
            if (count < 0 || 4 + count * 4 > n) return false;
            free(out->vox);
            out->vox = malloc((size_t)count * 4);
            if (!out->vox) { out->count = 0; return false; }
            memcpy(out->vox, c->d + body + 4, (size_t)count * 4);
            out->count = count;
        } else if (strcmp(id, "RGBA") == 0) {
            int entries = n / 4;
            if (entries > 256) entries = 256;
            for (int i = 0; i < entries; i++)
                memcpy(out->palette[i], c->d + body + i * 4, 4);
            out->hasPalette = true;
        } else if (strcmp(id, "MAIN") == 0) {
            if (!vox_walk(c, children, children + m, out, depth + 1)) return false;
        }
        /* PACK / nTRN / nGRP / MATL / rOBJ ... are skipped on purpose:
         * the bundled samples are plain single-model files */
        pos = children + m;
    }
    return true;
}

bool VoxParseMemory(const unsigned char *data, int len, VoxData *out) {
    memset(out, 0, sizeof(*out));
    if (!data || len < 20) return false;
    if (data[0] != 'V' || data[1] != 'O' || data[2] != 'X' || data[3] != ' ')
        return false;
    VoxCtx c = { data, len };
    if (!vox_walk(&c, 8, len, out, 0)) { VoxFree(out); return false; }
    if (out->sx <= 0 || out->sy <= 0 || out->sz <= 0 || out->count <= 0) {
        VoxFree(out);
        return false;
    }
    if (!out->hasPalette) {
        /* chr_cat.vox (and any file saved without an embedded palette)
         * uses the MagicaVoxel DEFAULT palette - embed it so such models
         * never fall back to garbage colours */
        memcpy(out->palette, VOX_DEFAULT_PALETTE, sizeof(VOX_DEFAULT_PALETTE));
        out->hasPalette = true;
    }
    return true;
}

bool VoxParseFile(const char *path, VoxData *out) {
    FILE *f = fopen(path, "rb");
    if (!f) return false;
    fseek(f, 0, SEEK_END);
    long len = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (len <= 0 || len > 64 * 1024 * 1024) { fclose(f); return false; }
    unsigned char *buf = malloc((size_t)len);
    if (!buf) { fclose(f); return false; }
    size_t got = fread(buf, 1, (size_t)len, f);
    fclose(f);
    bool ok = VoxParseMemory(buf, (int)got, out);
    free(buf);
    return ok;
}

void VoxFree(VoxData *v) {
    if (!v) return;
    free(v->vox);
    v->vox = NULL;
    v->count = 0;
}
